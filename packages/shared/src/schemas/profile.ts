import { z } from "zod";
import { CANDIDATE_QUALIFICATIONS, EMPLOYMENT_TYPES, ROLE_FAMILIES, WORKING_ARRANGEMENTS } from "../enums.js";

export const candidateProfileSchema = z.object({
  full_name: z.string().min(1).max(120).nullable(),
  email: z.string().email().nullable(),
  phone: z.string().max(40).nullable(),
  qualification: z.enum(CANDIDATE_QUALIFICATIONS),
  qualification_verified: z.boolean(),
  university: z.string().max(200).nullable(),
  graduation_year: z.number().int().min(1990).max(2100).nullable(),
  experience_years: z.number().min(0).max(40),
  experience_summary: z.string().max(2000).nullable(),
  software: z.array(z.string().max(60)),
  skills: z.array(z.string().max(60)),
  sector_interests: z.array(z.string().max(60)),
  target_role_families: z.array(z.enum(ROLE_FAMILIES)),
  accept_adjacent_entry_roles: z.boolean(),
  accepted_employment_types: z.array(z.enum(EMPLOYMENT_TYPES)),
  working_arrangement_preference: z.enum(WORKING_ARRANGEMENTS),
  objective: z.enum(["get_into_work_fast", "long_term_progression", "design_led", "technical_bim", "maximise_opportunities"]),
  home_postcode: z.string().max(10).nullable(),
  max_public_transport_minutes: z.number().int().min(15).max(240),
  max_car_minutes: z.number().int().min(15).max(240).nullable(),
  min_salary_gbp: z.number().int().min(0).nullable(),
  has_uk_right_to_work: z.boolean(),
  availability_from: z.string().nullable(),
  portfolio_url: z.string().url().nullable(),
  linkedin_url: z.string().url().nullable(),
});
export type CandidateProfile = z.infer<typeof candidateProfileSchema>;

